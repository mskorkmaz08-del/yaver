// Writes native/Yaver/Core/AnatomyData.swift from js/anatomy.js (the MIT-licensed
// react-native-body-highlighter muscle map). Paths are normalised with svgpath
// (npm i svgpath) to absolute M, L, C, Q and Z only, rounded to 0.1, and the back
// view is shifted to start at x 0, so Swift needs only a tiny path reader.
// Run: NODE_PATH=<folder with node_modules> node native/tools/gen_anatomy.mjs
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { ANATOMY } from '../../js/anatomy.js';
const svgpath = createRequire(import.meta.url)(process.env.NODE_PATH ? process.env.NODE_PATH + '/svgpath' : 'svgpath');

const r = n => Math.round(n * 10) / 10;
function norm(d, dx) {
  let out = [], x = 0, y = 0;
  svgpath(d).abs().unarc().unshort().translate(-dx, 0).iterate(seg => {
    const c = seg[0];
    if (c === 'H') { out.push(['L', seg[1], y]); x = seg[1]; return; }
    if (c === 'V') { out.push(['L', x, seg[1]]); y = seg[1]; return; }
    out.push(seg);
    if (c !== 'Z' && c !== 'z') { x = seg[seg.length - 2]; y = seg[seg.length - 1]; }
  });
  return out.map(s => s[0] + s.slice(1).map(r).join(' ')).join('');
}
const data = { front: {}, back: {}, outline: {} };
for (const side of ['front', 'back']) {
  const dx = side === 'front' ? 0 : 724;
  for (const [m, paths] of Object.entries(ANATOMY[side])) data[side][m] = paths.map(p => norm(p, dx));
  data.outline[side] = norm(ANATOMY.outline[side], dx);
}
const swift = `// Generated by native/tools/gen_anatomy.mjs from js/anatomy.js. Do not edit by hand.
// Muscle map paths from react-native-body-highlighter 3.2.0, MIT License,
// Copyright (c) 2022 ELABBASSI Hicham (full license text in js/anatomy.js).
// Each view is 724 x 1448. Paths use absolute M, L, C, Q and Z only.
import Foundation

enum AnatomyData {
    static let all: JSON = (try? JSON.decode(Data(raw.utf8))) ?? .null
    private static let raw = #"""
${JSON.stringify(data)}
"""#
}
`;
writeFileSync(new URL('../Yaver/Core/AnatomyData.swift', import.meta.url), swift);
console.log('AnatomyData.swift', swift.length);
