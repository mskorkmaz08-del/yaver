// Writes native/Yaver/Core/TrainingData.swift from js/training.js (exercises, sessions,
// muscle names), so the native training plan is the same as the web app's.
//   node native/tools/gen_training.mjs
import { writeFileSync } from 'node:fs';
const stub = () => new Proxy(function () {}, { get: (t, k) => k === Symbol.toPrimitive ? () => '' : k === 'then' ? undefined : stub(), apply: () => stub(), construct: () => stub() });
for (const g of ['document', 'window', 'localStorage', 'indexedDB', 'location', 'matchMedia']) if (!(g in globalThis)) globalThis[g] = stub();
const T = await import('../../js/training.js');
const json = JSON.stringify({ ex: T.EX, sessions: T.SESSIONS, muscles: T.MUSCLE_NAMES, mobility: T.MOBILITY });
writeFileSync(new URL('../Yaver/Core/TrainingData.swift', import.meta.url),
`// Generated by native/tools/gen_training.mjs from js/training.js. Do not edit by hand.
import Foundation

enum TrainingData {
    static let all: JSON = (try? JSON.decode(Data(raw.utf8))) ?? .null
    private static let raw = #"""
${json}
"""#
}
`);
console.log('wrote TrainingData.swift');
