// Writes native/Yaver/Core/NutrientInfo.swift from js/nutrients.js, so the native app's
// Why / Foods guide is the same text as the web app's. Run after editing js/nutrients.js:
//   node native/tools/gen_nutrients.mjs
import { writeFileSync } from 'node:fs';
import { INFO } from '../../js/nutrients.js';
const json = JSON.stringify(INFO);
if (json.includes('"""#')) throw new Error('nutrients text contains the Swift raw-string delimiter');
writeFileSync(new URL('../Yaver/Core/NutrientInfo.swift', import.meta.url),
`// Generated by native/tools/gen_nutrients.mjs from js/nutrients.js. Do not edit by hand.
import Foundation

enum NutrientInfo {
    struct Entry: Decodable { let why: String; let benefits: [String]; let low: String; let foods: [[String]] }
    static let all: [String: Entry] = (try? JSONDecoder().decode([String: Entry].self, from: Data(raw.utf8))) ?? [:]
    private static let raw = #"""
${json}
"""#
}
`);
console.log('wrote NutrientInfo.swift,', Object.keys(INFO).length, 'nutrients');
