// Writes native/Yaver/Core/AssistantDefs.swift from the web app: the assistant's fixed
// instructions (STATIC_SYSTEM in js/ai/claude.js) and every tool's name, description and
// input schema (js/ai/tools.js), so the native assistant offers exactly the same tools.
// Run after changing either file:  node native/tools/gen_assistant.mjs
import { writeFileSync } from 'node:fs';
const stub = () => new Proxy(function () {}, { get: (t, k) => k === Symbol.toPrimitive ? () => '' : k === 'then' ? undefined : stub(), apply: () => stub(), construct: () => stub() });
for (const g of ['document', 'window', 'localStorage', 'indexedDB', 'location', 'matchMedia', 'Notification', 'speechSynthesis']) if (!(g in globalThis)) globalThis[g] = stub();
const { toolDefinitions, WRITE_TOOLS } = await import('../../js/ai/tools.js');
const { STATIC_SYSTEM } = await import('../../js/ai/claude.js');
const tools = JSON.stringify(toolDefinitions);
for (const s of [tools, STATIC_SYSTEM]) if (s.includes('"""#')) throw new Error('text contains the Swift raw-string delimiter');
writeFileSync(new URL('../Yaver/Core/AssistantDefs.swift', import.meta.url),
`// Generated by native/tools/gen_assistant.mjs from js/ai/claude.js and js/ai/tools.js. Do not edit by hand.
import Foundation

enum AssistantDefs {
    static let system = #"""
${STATIC_SYSTEM}
"""#
    static let writeTools: Set<String> = [${[...WRITE_TOOLS].map(t => `"${t}"`).join(', ')}]
    static let tools: [JSON] = (try? JSON.decode(Data(toolsJSON.utf8)))?.array ?? []
    private static let toolsJSON = #"""
${tools}
"""#
}
`);
console.log('wrote AssistantDefs.swift:', toolDefinitions.length, 'tools');
